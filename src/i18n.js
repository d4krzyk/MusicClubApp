export const I18nCtx = createContext({ lang: 'pl', t: (k) => k });
export const useT = () => useContext(I18nCtx);

export function translator(lang) {
  const i = lang === 'en' ? 1 : 0;
  return (klucz, ...args) => {
    const w = S[klucz];
    const tekst = w ? w[i] : klucz;
    return tekst.replace(/\{(\d+)\}/g, (m, n) => (args[n] ?? m));
  };
}

export function detectLang(saved) {
  if (saved === 'pl' || saved === 'en') return saved;
  try { return (navigator.language ?? 'pl').toLowerCase().startsWith('pl') ? 'pl' : 'en'; } catch { return 'pl'; }
}

