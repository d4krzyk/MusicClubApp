--  Klany.
--
--  clans               - klan; kolor to wynik glosowania czlonkow (przeliczany przez aplikacje).
--  clan_members        - czlonkostwo; unikalny user_id = jeden klan na osobe.
--  clan_invitations    - zaproszenia (jedyna droga do klanu); DECLINED zostaje, zeby nie zapraszac
--                        w kolko osoby, ktora odmowila.
--  clan_messages       - czat klanu.
--  posts.clan_id       - post klanu (widoczny tylko dla czlonkow, nie ma go na tablicy).
--  notifications       - zaproszenie do klanu i wyrzucenie (clan_id znika razem z klanem).
--  users.clan_invites_from - kto moze mnie zaprosic do klanu (domyslnie kazdy).
-- =============================================================================

