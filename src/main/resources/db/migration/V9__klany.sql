CREATE TABLE clans (
    tag character varying(5) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    id bigint NOT NULL,
    color character varying(16) NOT NULL,
    name character varying(32) NOT NULL,
    name_key character varying(64) NOT NULL,
    icon_file_name character varying(100),
    photo_file_name character varying(100),
    description character varying(300),
    CONSTRAINT clans_color_check CHECK (((color)::text = ANY ((ARRAY['VIOLET'::character varying, 'PINK'::character varying, 'RED'::character varying, 'ORANGE'::character varying, 'AMBER'::character varying, 'GREEN'::character varying, 'TEAL'::character varying, 'BLUE'::character varying, 'INDIGO'::character varying, 'SLATE'::character varying])::text[])))
);

ALTER TABLE clans ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME clans_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY clans
    ADD CONSTRAINT clans_pkey PRIMARY KEY (id);

ALTER TABLE ONLY clans
    ADD CONSTRAINT uk_clans_name_key UNIQUE (name_key);

ALTER TABLE ONLY clans
